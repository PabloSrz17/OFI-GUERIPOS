/**
 * Escritor mínimo de Excel (.xlsx) sin dependencias: una hoja con encabezados en negrita, anchos de columna
 * calculados, fila de encabezado fija y filtros. Las columnas de dinero se guardan como número con formato
 * "$#,##0.00" (Excel puede sumarlas). El archivo es un ZIP sin compresión con los XML de Office Open XML.
 */
export interface XlsxColumn {
  header: string;
  /** `money`: número con formato de moneda. */
  type?: 'text' | 'money';
}

export type XlsxCell = string | number | null;

const xmlEsc = (s: string) =>
  s
    .replace(/[\u0000-\u0008\u000b\u000c\u000e-\u001f]/g, '')
    .replace(/[&<>"]/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' })[c]!);

/** A, B, …, Z, AA… */
const colName = (i: number): string => (i < 26 ? String.fromCharCode(65 + i) : colName(Math.floor(i / 26) - 1) + String.fromCharCode(65 + (i % 26)));

const moneyText = (n: number) => '$' + n.toLocaleString('en-US', { minimumFractionDigits: 2, maximumFractionDigits: 2 });

/** Ancho en "caracteres" de Excel: lo más largo de la columna + margen (la negrita y el botón de filtro ocupan más). */
export function columnWidths(columns: XlsxColumn[], rows: XlsxCell[][]): number[] {
  return columns.map((c, i) => {
    let max = c.header.length + 4;
    for (const r of rows) {
      const v = r[i];
      const len = v === null || v === undefined ? 0 : c.type === 'money' && typeof v === 'number' ? moneyText(v).length + 2 : String(v).length;
      if (len > max) max = len;
    }
    return Math.min(80, Math.max(10, max + 2));
  });
}

function sheetXml(columns: XlsxColumn[], rows: XlsxCell[][]) {
  const widths = columnWidths(columns, rows);
  const last = colName(columns.length - 1);
  const cell = (ref: string, v: XlsxCell, style: number, money: boolean) => {
    if (v === null || v === undefined || v === '') return style ? `<c r="${ref}" s="${style}"/>` : '';
    if (typeof v === 'number' && Number.isFinite(v)) return `<c r="${ref}" s="${money ? 2 : style}"><v>${v}</v></c>`;
    return `<c r="${ref}" t="inlineStr"${style ? ` s="${style}"` : ''}><is><t xml:space="preserve">${xmlEsc(String(v))}</t></is></c>`;
  };
  const header = `<row r="1">${columns.map((c, i) => cell(`${colName(i)}1`, c.header, 1, false)).join('')}</row>`;
  const body = rows
    .map((r, ri) => `<row r="${ri + 2}">${columns.map((c, i) => cell(`${colName(i)}${ri + 2}`, r[i] ?? null, c.type === 'money' ? 2 : 0, c.type === 'money')).join('')}</row>`)
    .join('');
  return (
    '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>' +
    '<worksheet xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main" xmlns:r="http://schemas.openxmlformats.org/officeDocument/2006/relationships">' +
    `<dimension ref="A1:${last}${rows.length + 1}"/>` +
    '<sheetViews><sheetView workbookViewId="0"><pane ySplit="1" topLeftCell="A2" activePane="bottomLeft" state="frozen"/></sheetView></sheetViews>' +
    '<sheetFormatPr defaultRowHeight="15"/>' +
    `<cols>${widths.map((w, i) => `<col min="${i + 1}" max="${i + 1}" width="${w}" customWidth="1"/>`).join('')}</cols>` +
    `<sheetData>${header}${body}</sheetData>` +
    `<autoFilter ref="A1:${last}${rows.length + 1}"/>` +
    '</worksheet>'
  );
}

